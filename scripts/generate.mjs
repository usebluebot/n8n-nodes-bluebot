#!/usr/bin/env node
/**
 * Writes what this package builds from the API manifest, so a new event type, message state, source or delivery
 * state reaches the nodes' dropdowns by running this script (or `node packages/codegen/regenerate.mjs` at the
 * repository root) instead of by hand:
 *
 *   nodes/shared/api.generated.ts    the dropdown options the nodes use
 *   test/examples.generated.json     each operation's and event's example, which the tests answer requests with
 *
 * Reads ../../packages/codegen/manifest.json (built from public/openapi.v1.json). Uses only Node's standard library.
 * `node scripts/generate.mjs --check` writes nothing and exits 1 when either file is stale.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const PACKAGE_ROOT = resolve(here, '..');
export const MANIFEST_PATH = resolve(PACKAGE_ROOT, '..', '..', 'packages', 'codegen', 'manifest.json');
export const OPTIONS_PATH = resolve(PACKAGE_ROOT, 'nodes', 'shared', 'api.generated.ts');
export const EXAMPLES_PATH = resolve(PACKAGE_ROOT, 'test', 'examples.generated.json');

/** Words that keep their own spelling in a label. */
const SPELLINGS = {
    api: 'API',
    cli: 'CLI',
    mcp: 'MCP',
    n8n: 'n8n',
    mac: 'Mac',
    sms: 'SMS',
    imessage: 'iMessage',
    ok: 'OK',
};

function label(value) {
    return value
        .split(/[_\s.]+/)
        .filter(Boolean)
        .map((word) => SPELLINGS[word.toLowerCase()] ?? word.charAt(0).toUpperCase() + word.slice(1))
        .join(' ');
}

/**
 * The first sentence of a description, without Markdown code marks or the final period, as n8n's option
 * descriptions are written. One that starts with a lower-case word (iMessage) gets a lead-in, since n8n's lint
 * asks for a capital first letter and capitalizing the word would misspell it.
 */
function firstSentence(text) {
    const plain = String(text ?? '')
        .replace(/`/g, '')
        .replace(/\s+/g, ' ')
        .trim();
    const end = plain.search(/\.(\s|$)/);
    const sentence = (end === -1 ? plain : plain.slice(0, end)).replace(/\.$/, '');
    return /^[a-z]/.test(sentence) ? `When ${sentence}` : sentence;
}

function byName(a, b) {
    return a.name.localeCompare(b.name, 'en');
}

function queryEnum(manifest, operationId, parameter) {
    const operation = manifest.operations.find((o) => o.operationId === operationId);
    if (!operation) throw new Error(`The manifest has no operation ${operationId}.`);
    const query = operation.query.find((q) => q.name === parameter);
    const values = query?.schema?.enum;
    if (!Array.isArray(values)) throw new Error(`${operationId} has no enum for ${parameter}.`);
    return values;
}

function optionsLiteral(options) {
    return options
        .map((option) => {
            const fields = [`name: ${JSON.stringify(option.name)}`, `value: ${JSON.stringify(option.value)}`];
            if (option.description) fields.push(`description: ${JSON.stringify(option.description)}`);
            const line = `\t{ ${fields.join(', ')} },`;
            // n8n writes its own name in lower case; the title-case rule would make it "N8n".
            return /^[a-z]/.test(option.name) ? `\t// eslint-disable-next-line n8n-nodes-base/node-param-display-name-miscased\n${line}` : line;
        })
        .join('\n');
}

/** The contents of both generated files for a manifest. */
export function render(manifest) {
    const eventOptions = manifest.events
        .map((event) => ({ name: label(event.summary), value: event.type, description: firstSentence(event.description) }))
        .sort(byName);
    const stateOptions = queryEnum(manifest, 'listMessages', 'state')
        .map((value) => ({ name: label(value), value }))
        .sort(byName);
    const sourceOptions = queryEnum(manifest, 'listMessages', 'source')
        .map((value) => ({ name: label(value), value }))
        .sort(byName);
    const deliveryStateOptions = queryEnum(manifest, 'listDeliveries', 'state')
        .map((value) => ({ name: label(value), value }))
        .sort(byName);

    const options = `// Generated by scripts/generate.mjs from packages/codegen/manifest.json (${manifest.generatedFrom}, API ${manifest.apiVersion}).
// Don't edit it by hand: run \`npm run generate\` in integrations/n8n, or \`node packages/codegen/regenerate.mjs\` at the repository root.

import type { INodePropertyOptions } from 'n8n-workflow';

/** The API version the manifest was built from. */
export const API_VERSION = ${JSON.stringify(manifest.apiVersion)};

/** Every webhook event type BlueBot sends. */
export const EVENT_TYPES = ${JSON.stringify(manifest.eventTypes)} as const;

export type EventType = (typeof EVENT_TYPES)[number];

/** Every event type as an option, sorted by name. */
export const EVENT_OPTIONS: INodePropertyOptions[] = [
${optionsLiteral(eventOptions)}
];

/** Every state a text can be in. */
export const MESSAGE_STATE_OPTIONS: INodePropertyOptions[] = [
${optionsLiteral(stateOptions)}
];

/** Every source a text can have. */
export const MESSAGE_SOURCE_OPTIONS: INodePropertyOptions[] = [
${optionsLiteral(sourceOptions)}
];

/** Every state a webhook delivery can be in. */
export const DELIVERY_STATE_OPTIONS: INodePropertyOptions[] = [
${optionsLiteral(deliveryStateOptions)}
];
`;

    const examples = {
        apiVersion: manifest.apiVersion,
        operations: Object.fromEntries(
            manifest.operations.map((operation) => [
                operation.operationId,
                {
                    method: operation.method.toUpperCase(),
                    path: operation.path,
                    status: operation.response?.status ?? 200,
                    request: operation.body?.example ?? null,
                    response: operation.response?.example ?? null,
                },
            ]),
        ),
        events: Object.fromEntries(manifest.events.map((event) => [event.type, event.example])),
        errors: Object.fromEntries(manifest.errorCodes.map((error) => [error.code, { status: error.status, hint: error.hint, doc_url: error.doc_url }])),
    };

    return { options, examples: `${JSON.stringify(examples, null, '\t')}\n` };
}

function main() {
    const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));
    const { options, examples } = render(manifest);
    if (process.argv.includes('--check')) {
        const stale = [
            [OPTIONS_PATH, options],
            [EXAMPLES_PATH, examples],
        ].filter(([path, content]) => !existsSync(path) || readFileSync(path, 'utf8') !== content);
        for (const [path] of stale) console.error(`n8n: ${path} is stale; run npm run generate.`);
        process.exit(stale.length ? 1 : 0);
    }
    writeFileSync(OPTIONS_PATH, options);
    writeFileSync(EXAMPLES_PATH, examples);
    console.log(
        `n8n: wrote nodes/shared/api.generated.ts and test/examples.generated.json (${manifest.events.length} event types, ${manifest.operations.length} operations)`,
    );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
